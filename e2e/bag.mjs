import { chromium } from 'playwright-core';
import fs from 'node:fs';
// The bag: B opens it, the bag shows on her, F at the wardrobe at home changes the bag (what she carries moves over, the
// rest stays in the wardrobe), the clerk's shop sells things for yen, and it all stays when she changes world. OUT=dir.
const OUT = process.env.OUT || 'e2e/out';
fs.mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-angle=swiftshader', '--use-gl=angle', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 900, height: 620 } });
const errs = []; page.on('pageerror', (e) => errs.push(e.message)); page.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
let bad = 0;
const ok = (name, cond, extra) => { if (!cond) bad++; console.log(cond ? 'OK  ' : 'FAIL', name, extra ?? ''); };
const ready = () => page.waitForFunction(() => window.__game && window.__game.frames() > 4, null, { timeout: 240000 });
const frames = async (n) => { const f0 = await page.evaluate(() => window.__game.frames()); await page.waitForFunction((t) => window.__game.frames() >= t, f0 + n, { timeout: 120000 }); };
const inv = () => page.evaluate(() => { const s = window.__game.inv.state; return { bag: s.bag, slots: s.slots.length, items: s.slots.filter(Boolean).map((x) => `${x.id}:${x.n}`), stash: s.stash.map((x) => `${x.id}:${x.n}`), yen: s.yen }; });

await page.goto('http://localhost:5300/?world=home&q=low&pause=1&t=12');
await page.evaluate(() => localStorage.removeItem('hoshi.bag'));
await page.reload(); await ready(); await frames(3);
let s = await inv();
ok('she starts with the school bag and a few things', s.bag === 'school' && s.slots === 10 && s.items.length === 4 && s.yen === 3000, JSON.stringify(s));
ok('the bag is on her back', await page.evaluate(() => window.__game.player.group.children.some((c) => c.name === 'Bag school')));
await page.keyboard.press('KeyB');
await frames(2);
ok('B opens the bag, and she stands still', await page.evaluate(() => document.getElementById('bag').classList.contains('on') && window.__game.player.frozen));
ok('with ten slots', (await page.$$('#bag .slot')).length === 10);
await page.click('#bag .slot:not(.empty)');
ok('a click shows the thing, with a Use button for food', await page.evaluate(() => /House keys|Onigiri|Notebook|coffee/i.test(document.querySelector('#bag .info').textContent)));
await page.screenshot({ path: `${OUT}/bag-open.png` });
await page.keyboard.press('Escape');
await frames(2);
ok('Esc closes it and frees her', await page.evaluate(() => !document.getElementById('bag').classList.contains('on') && !window.__game.player.frozen));

// the wardrobe
await page.evaluate(() => window.__game.player.teleport(2.8, 3.0));
await frames(3);
ok('at the wardrobe there is a prompt', await page.evaluate(() => document.getElementById('act').classList.contains('on') && /Wardrobe/.test(document.getElementById('act').textContent)));
await page.keyboard.press('KeyF');
await frames(2);
ok('F opens the wardrobe', await page.evaluate(() => document.getElementById('bag').classList.contains('on') && document.querySelectorAll('#bag .bagcard').length === 4));
await page.screenshot({ path: `${OUT}/bag-wardrobe.png` });
await page.click('#bag [data-bag="tote"]');
s = await inv();
ok('the tote bag has six slots, and her things moved over', s.bag === 'tote' && s.slots === 6 && s.items.length === 4, JSON.stringify(s));
await page.click('#bag [data-store="0"]');
await page.click('#bag [data-store="1"]');
await page.click('#bag [data-store="2"]');
s = await inv();
ok('putting things away fills the wardrobe', s.stash.length === 3 && s.items.length === 1, JSON.stringify(s));
await page.click('#bag [data-bag="backpack"]');
s = await inv();
ok('the backpack has sixteen slots', s.bag === 'backpack' && s.slots === 16, JSON.stringify(s));
ok('and she wears it', await page.evaluate(() => window.__game.player.group.children.some((c) => c.name === 'Bag backpack') && !window.__game.player.group.children.some((c) => c.name === 'Bag school')));
await page.click('#bag [data-take="0"]');
s = await inv();
ok('taking from the wardrobe puts it in the bag', s.stash.length === 2 && s.items.length === 2, JSON.stringify(s));
// fill the bag, then switch to a smaller one: what does not fit goes to the wardrobe
await page.evaluate(() => { const i = window.__game.inv; for (const id of ['onigiri', 'bento', 'coffee', 'tea', 'bread', 'icecream', 'umbrella']) i.add(id, 3); });
await page.click('#bag [data-bag="tote"]');
s = await inv();
ok('a smaller bag leaves the overflow in the wardrobe', s.slots === 6 && s.items.length === 6 && s.stash.length >= 4, JSON.stringify(s));
await page.keyboard.press('Escape');
await page.screenshot({ path: `${OUT}/bag-worn.png` });

// it stays across worlds (each world is a page of its own)
await page.goto('http://localhost:5300/?world=konbini&q=low&pause=1&t=12');
await ready(); await frames(3);
s = await inv();
ok('the bag is the same in the shop', s.bag === 'tote' && s.items.length === 6, JSON.stringify(s));
// the shop, the way a real one goes: a basket by the door, shelves with their own things, pay at the register
const at = async (x, z) => { await page.evaluate(([x, z]) => { const g = window.__game; g.player.teleport(x, z); }, [x, z]); await frames(3); };
const act = () => page.evaluate(() => { const e = document.getElementById('act'); return e.classList.contains('on') ? e.textContent : ''; });
const mode = () => page.evaluate(() => window.__game.bagUi.mode);
const baskets = () => page.evaluate(() => { const b = window.__game.bagUi.basket; return { has: b.has, count: b.count, total: b.total, items: b.items.map((x) => `${x.id}:${x.n}`) }; });
await page.evaluate(() => { const i = window.__game.inv; i.state.slots = i.state.slots.map(() => null); i.state.yen = 3000; i.add('keys', 1); });
await at(0.4, -1.2);
ok('at a shelf without a basket the prompt asks for a basket first', /basket first/i.test(await act()), await act());
await page.keyboard.press('KeyF'); await frames(2);
ok('and F does not open the shelf', (await mode()) === null);
await at(-4.0, -2.9);
ok('by the door there is a stack of baskets', /Take a basket/.test(await act()), await act());
await page.keyboard.press('KeyF'); await frames(2);
let b = await baskets();
ok('F takes one, and she carries it', b.has && await page.evaluate(() => window.__game.player.group.children.some((c) => c.name === 'Basket')));
await at(0.4, -1.2);
ok('each shelf has its own prompt', /Snacks and bread/.test(await act()), await act());
await page.keyboard.press('KeyF'); await frames(2);
ok('F opens the shelf: snacks and bread (5 things)', (await mode()) === 'shelf' && (await page.$$('#bag .rows .row')).length === 5);
await page.click('#bag [data-add="chips"]'); await page.click('#bag [data-add="chips"]'); await page.click('#bag [data-add="bread"]');
b = await baskets();
ok('adding puts things in the basket (not the bag yet)', b.count === 3 && b.total === 140 * 2 + 160 && (await inv()).items.length === 1, JSON.stringify(b));
await page.screenshot({ path: `${OUT}/bag-shelf.png` });
await page.keyboard.press('Escape'); await frames(2);
await at(0.4, 2.7);
ok('the drinks cooler sells other things', /Drinks/.test(await act()), await act());
await page.keyboard.press('KeyF'); await frames(2);
ok('coffee, tea, soda, milk, juice', (await mode()) === 'shelf' && (await page.$$('#bag [data-add]')).length === 5 && !!(await page.$('#bag [data-add="soda"]')));
await page.click('#bag [data-add="soda"]');
await page.keyboard.press('Escape'); await frames(2);
await at(4.0, 0.2);
ok('the chilled case has onigiri and bento', /Fresh food/.test(await act()), await act());
// leaving with an unpaid basket is not allowed
await at(-3, -3.5);
await page.keyboard.press('Enter'); await frames(3);
ok('she cannot leave with an unpaid basket', (await page.evaluate(() => window.__game.hud.world.key)) === 'konbini' && /Pay for/.test(await act()), await act());
// the register
await at(2.8, -1.1);
ok('at the register: pay', /register/i.test(await act()), await act());
await page.keyboard.press('KeyF'); await frames(2);
ok('F shows the basket and the total', (await mode()) === 'register' && (await page.$$('#bag .rows .row')).length === 3);
const yen0 = (await inv()).yen, total = (await baskets()).total;
await page.screenshot({ path: `${OUT}/bag-register.png` });
await page.click('#bag [data-pay]');
s = await inv(); b = await baskets();
ok('paying takes the money and puts the things in the bag', s.yen === yen0 - total && s.items.includes('chips:2') && s.items.includes('bread:1') && s.items.includes('soda:1') && !b.has, JSON.stringify({ s, b }));
ok('the basket is returned (she no longer carries it)', await page.evaluate(() => !window.__game.player.group.children.some((c) => c.name === 'Basket')));
await page.keyboard.press('Escape'); await frames(2);
// not enough money, and a full bag
await at(-4.0, -2.9); await page.keyboard.press('KeyF'); await frames(2);
await at(4.0, 0.2); await page.keyboard.press('KeyF'); await frames(2);
await page.click('#bag [data-add="bento"]');
await page.keyboard.press('Escape'); await frames(2);
await page.evaluate(() => { window.__game.inv.state.yen = 100; });
await at(2.8, -1.1); await page.keyboard.press('KeyF'); await frames(2);
const items0 = (await inv()).items.join();
await page.click('#bag [data-pay]');
ok('without enough money the payment fails and nothing changes', /Not enough money/.test(await page.evaluate(() => document.querySelector('#bag .msg').textContent)) && (await inv()).items.join() === items0 && (await baskets()).count === 1);
await page.evaluate(() => { const i = window.__game.inv; i.state.yen = 3000; i.state.slots = i.state.slots.map((_, k) => ({ id: ['keys', 'notebook', 'pen', 'tissue', 'battery', 'mask', 'umbrella', 'magazine', 'newspaper', 'candy', 'chocolate', 'chips', 'milk', 'juice', 'salad', 'sandwich'][k], n: 1 })); });
await page.click('#bag [data-pay]');
ok('with a full bag the payment fails too', /too full/.test(await page.evaluate(() => document.querySelector('#bag .msg').textContent)) && (await baskets()).count === 1);
await page.keyboard.press('Escape'); await frames(2);
// give the basket back at the door: she can leave
await at(-4.0, -2.9); await page.keyboard.press('KeyF'); await frames(2);
b = await baskets();
ok('putting the basket back returns the things to the shelves', !b.has && b.count === 0);
await at(-3, -3.5);
await page.keyboard.press('Enter');
await page.waitForFunction(() => window.__game && window.__game.hud.world.key === 'ekimae' && window.__game.frames() > 4, null, { timeout: 240000 });
ok('and she can leave the shop', true);
ok('no page errors', errs.filter((e) => !/Failed to fetch/.test(e)).length === 0, errs.slice(0, 3).join(' | '));
await browser.close();
process.exit(bad ? 1 : 0);
