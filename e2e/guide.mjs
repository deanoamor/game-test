import { chromium } from 'playwright-core';
import fs from 'node:fs';
// The guide of the game (not dev mode): an introduction at the start, then an objective list with a beam in the world and an
// arrow at the screen edge that leads her home, to the wardrobe, out, to the Hoshi Mart, and through a basket, a shelf and
// the register. Runs in game mode. Start the dev server first. OUT=dir.
const OUT = process.env.OUT || 'e2e/out';
fs.mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-angle=swiftshader', '--use-gl=angle', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1000, height: 640 } });
const errs = []; page.on('pageerror', (e) => errs.push(e.message)); page.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
let bad = 0;
const ok = (name, cond, extra) => { if (!cond) bad++; console.log(cond ? 'OK  ' : 'FAIL', name, extra ?? ''); };
const ready = () => page.waitForFunction(() => window.__game && window.__game.frames() > 5, null, { timeout: 240000 });
const frames = async (n) => { const f0 = await page.evaluate(() => window.__game.frames()); await page.waitForFunction((t) => window.__game.frames() >= t, f0 + n, { timeout: 120000 }); };
const quest = () => page.evaluate(() => ({ on: document.getElementById('quest').classList.contains('on'), text: document.querySelector('#quest b')?.textContent, n: document.querySelector('#quest .n')?.textContent, dist: document.querySelector('#quest .dist')?.textContent, world: window.__game.hud.world.key, beam: window.__game.guide?.group.visible }));
const at = async (x, z) => { await page.evaluate(([x, z]) => { const g = window.__game; g.player.teleport(x, z); g.hud.update(0.016, 15, 0, g.player.pos); }, [x, z]); await frames(3); };

await page.goto('http://localhost:5300/');
await page.evaluate(() => { localStorage.clear(); sessionStorage.clear(); });
await page.reload();
await ready(); await frames(3);
ok('the introduction is up, and she stands still', await page.evaluate(() => !!document.getElementById('intro') && window.__game.player.frozen));
ok('it says what to do and the keys', await page.evaluate(() => /find your way home/i.test(document.getElementById('intro').textContent) && /Hoshi Mart/.test(document.getElementById('intro').textContent) && document.querySelectorAll('#intro kbd').length > 6));
await page.screenshot({ path: `${OUT}/guide-intro.png` });
ok('no objective yet', !(await quest()).on);
await page.keyboard.press('Enter');
await frames(3);
let q = await quest();
ok('Enter starts the game: she is free', await page.evaluate(() => !document.getElementById('intro') && !window.__game.player.frozen));
ok('the first objective: go home (1/7), with the beam and a distance', q.on && q.text === 'Go home' && q.n === '1/7' && q.beam && /m$/.test(q.dist), JSON.stringify(q));
await page.screenshot({ path: `${OUT}/guide-home.png` });
const door = await page.evaluate(() => { const d = window.__game.hud.world.exits.find((e) => e.to === 'home').at; return [(d.x0 + d.x1) / 2, (d.z0 + d.z1) / 2]; });
const beam = await page.evaluate(() => { const p = window.__game.guide.group.position; return [p.x, p.z]; });
ok('the beam stands at the door of her home', Math.hypot(beam[0] - door[0], beam[1] - door[1]) < 0.5, JSON.stringify({ beam, door }));
ok('the mark is on the screen (the beam over the door, or an arrow at the edge)', await page.evaluate(() => document.getElementById('guideMark').classList.contains('on')));
// at the door of her home
await at(door[0], door[1]);
await page.keyboard.press('Enter');
await page.waitForFunction(() => window.__game && window.__game.hud.world.key === 'home' && window.__game.frames() > 4, null, { timeout: 240000 });
await frames(4);
q = await quest();
ok('in her home: look at the wardrobe (2/7)', q.world === 'home' && q.text === 'Look at your wardrobe' && q.n === '2/7', JSON.stringify(q));
await at(2.8, 3.0);
await page.keyboard.press('KeyF'); await frames(3);
await page.keyboard.press('Escape'); await frames(3);
q = await quest();
ok('after opening it: go back out (3/7)', q.text === 'Go back out' && q.n === '3/7', JSON.stringify(q));
await at(-3.1, -3.5);
await page.keyboard.press('Enter');
await page.waitForFunction(() => window.__game && window.__game.hud.world.key === 'ekimae' && window.__game.frames() > 4, null, { timeout: 240000 });
await frames(4);
q = await quest();
ok('out on the street: the Hoshi Mart (4/7)', q.world === 'ekimae' && q.text === 'Go to the Hoshi Mart' && q.n === '4/7', JSON.stringify(q));
const kd = await page.evaluate(() => { const d = window.__game.hud.world.exits.find((e) => e.to === 'konbini').at; return [(d.x0 + d.x1) / 2, (d.z0 + d.z1) / 2]; });
const beam2 = await page.evaluate(() => { const p = window.__game.guide.group.position; return [p.x, p.z]; });
ok('the beam is at the shop door', Math.hypot(beam2[0] - kd[0], beam2[1] - kd[1]) < 0.5);
await at(kd[0], kd[1]);
await page.keyboard.press('Enter');
await page.waitForFunction(() => window.__game && window.__game.hud.world.key === 'konbini' && window.__game.frames() > 4, null, { timeout: 240000 });
await frames(4);
q = await quest();
ok('in the shop: take a basket (5/7)', q.world === 'konbini' && q.text === 'Take a basket' && q.n === '5/7', JSON.stringify(q));
await page.screenshot({ path: `${OUT}/guide-shop.png` });
await at(-4.0, -2.9); await page.keyboard.press('KeyF'); await frames(3);
q = await quest();
ok('with a basket: pick something (6/7)', q.text === 'Pick something from a shelf' && q.n === '6/7', JSON.stringify(q));
await at(4.0, 0.2); await page.keyboard.press('KeyF'); await frames(3);
await page.click('#bag [data-add="onigiri"]');
await page.keyboard.press('Escape'); await frames(3);
q = await quest();
ok('with something in it: pay at the register (7/7)', q.text === 'Pay at the register' && q.n === '7/7', JSON.stringify(q));
await at(2.8, -1.1); await page.keyboard.press('KeyF'); await frames(3);
await page.click('#bag [data-pay]'); await frames(3);
await page.keyboard.press('Escape'); await frames(4);
q = await quest();
ok('after paying the list is done: no objective, no beam', !q.on && !q.beam, JSON.stringify(q));
ok('the progress is kept: a new page does not bring the introduction or the list back', await (async () => { await page.goto('http://localhost:5300/'); await ready(); await frames(3); return page.evaluate(() => !document.getElementById('intro') && !document.getElementById('quest').classList.contains('on')); })());
// the skip button
await page.evaluate(() => { localStorage.setItem('hoshi.guide', JSON.stringify({ step: 0, seen: true })); });
await page.reload(); await ready(); await frames(4);
ok('with the list on again, the ✕ hides it for good', await (async () => { await page.click('#quest .skip'); await frames(3); return page.evaluate(() => !document.getElementById('quest').classList.contains('on')); })());
ok('no page errors', errs.length === 0, errs.slice(0, 3).join(' | '));
await browser.close();
process.exit(bad ? 1 : 0);
